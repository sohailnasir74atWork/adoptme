#!/usr/bin/env node
// Regenerates the safe_chat_templates seed block from the JS catalogue so the
// client list and the list Postgres validates against cannot drift.
//
//   node scripts/gen-safe-templates-sql.js            # print the block
//   node scripts/gen-safe-templates-sql.js --write    # splice it into the migration
//
// The migration keeps the block between the two SEED markers; everything
// outside them is left alone.

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const SRC = path.join(ROOT, 'Code/ChatScreen/safeTemplates.js');
const MIGRATION = path.join(ROOT, 'supabase/028_safe_chat_minors.sql');
const BEGIN = '-- >>> SEED BEGIN (generated by scripts/gen-safe-templates-sql.js) <<<';
const END = '-- >>> SEED END <<<';

// The catalogue is an ES module and this script is CJS, so strip the `export`
// keywords and evaluate it. Cheaper and less brittle than adding a build step
// for one array of strings.
function loadTemplates() {
  const src = fs.readFileSync(SRC, 'utf8').replace(/^export /gm, '');
  const mod = { exports: {} };
  // eslint-disable-next-line no-new-func
  new Function('module', 'exports', `${src}\nmodule.exports = { SAFE_TEMPLATES };`)(mod, mod.exports);
  return mod.exports.SAFE_TEMPLATES;
}

const sqlQuote = (s) => `'${String(s).replace(/'/g, "''")}'`;

function buildSeed(templates) {
  const rows = templates
    .map((t) => `  (${sqlQuote(t.id)}, ${sqlQuote(t.en)}, ${sqlQuote(t.category)})`)
    .join(',\n');
  return [
    BEGIN,
    'insert into public.safe_chat_templates (id, text_en, category) values',
    rows + '',
    'on conflict (id) do update',
    '  set text_en  = excluded.text_en,',
    '      category = excluded.category;',
    '',
    '-- Anything no longer in the catalogue stops being sendable. Existing',
    '-- messages that used it are untouched — this table only gates new inserts.',
    'delete from public.safe_chat_templates',
    ` where id not in (${templates.map((t) => sqlQuote(t.id)).join(', ')});`,
    END,
  ].join('\n');
}

const templates = loadTemplates();
const seed = buildSeed(templates);

if (!process.argv.includes('--write')) {
  console.log(seed);
  process.exit(0);
}

const sql = fs.readFileSync(MIGRATION, 'utf8');
const start = sql.indexOf(BEGIN);
const stop = sql.indexOf(END);
if (start === -1 || stop === -1) {
  console.error(`Markers not found in ${MIGRATION}`);
  process.exit(1);
}
fs.writeFileSync(MIGRATION, sql.slice(0, start) + seed + sql.slice(stop + END.length));
console.log(`Wrote ${templates.length} templates into ${path.relative(ROOT, MIGRATION)}`);
