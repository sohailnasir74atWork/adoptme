def update_nested(data, key_path, value):
    keys = key_path.split('.')
    current = data
    for i, key in enumerate(keys[:-1]):
        if key not in current:
            current[key] = {}
        current = current[key]
        if not isinstance(current, dict):
             # Force it to be a dict if it was a string (conflict resolution)
             # But this is risky. Let's assume structure matches unless conflict.
             # If current is string, we can't attach children.
             print(f"Warning: Conflict at {key_path}. {key} is {type(current)}")
             return
    current[keys[-1]] = value

for lang, additions in new_translations.items():
    file_path = os.path.join(base_path, f'{lang}.json')
    if os.path.exists(file_path):
        print(f"Updating {lang}.json...")
        data = load_json(file_path)
        
        for key, value in additions.items():
            update_nested(data, key, value)
            
        save_json(file_path, data)
        print(f"Saved {lang}.json")
    else:
        print(f"File not found: {file_path}")

print("Update Complete.")
